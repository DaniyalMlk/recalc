import { describe, expect, it } from "vitest";
import { Workbook } from "../src/engine/workbook.js";
import { civilFromSerial, serialFromCivil } from "../src/date/serial.js";
import { basisDays, yearFraction } from "../src/date/daycount.js";
import type { DayCountBasis } from "../src/date/daycount.js";
import { couponPeriodDays, quasiCouponSpans } from "../src/date/coupons.js";
import type { CouponFrequency } from "../src/date/coupons.js";
import { accruedYears } from "../src/functions/bonds.js";

const s = (y: number, m: number, d: number) => serialFromCivil(y, m, d);

const iso = (serial: number): string => {
  const { year, month, day } = civilFromSerial(serial);
  return `${year}-${String(month).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
};

function sheet() {
  const book = new Workbook();
  return {
    num(formula: string): number {
      book.setCell("Z100", formula);
      const value = book.getValue("Z100");
      if (typeof value !== "number") {
        throw new Error(`${formula} produced ${JSON.stringify(value)}`);
      }
      return value;
    },
    display(formula: string): string {
      book.setCell("Z100", formula);
      return book.getDisplay("Z100");
    },
  };
}

const plain = sheet();
const ALL_BASES: readonly DayCountBasis[] = [0, 1, 2, 3, 4];
const FREQUENCIES: readonly CouponFrequency[] = [1, 2, 4];

/**
 * A deterministic sweep of accruals: every combination of a start date through
 * two years, four span lengths, five first-interest dates and three
 * frequencies. Fixed rather than random, so a failure names one case.
 */
function sweep(): readonly {
  readonly issue: number;
  readonly settlement: number;
  readonly first: number;
  readonly frequency: CouponFrequency;
}[] {
  const base = s(2024, 1, 1);
  const cases: {
    issue: number;
    settlement: number;
    first: number;
    frequency: CouponFrequency;
  }[] = [];
  for (let offset = 0; offset < 760; offset += 7) {
    for (const length of [40, 200, 420, 700]) {
      for (const ahead of [95, 190, 260, 400, 580]) {
        for (const frequency of FREQUENCIES) {
          cases.push({
            issue: base + offset,
            settlement: base + offset + length,
            first: base + offset + ahead,
            frequency,
          });
        }
      }
    }
  }
  return cases;
}

const CASES = sweep();

describe("the quasi-coupon spans an accrual is broken on", () => {
  it("sweeps enough cases to be a sweep", () => {
    expect(CASES.length).toBe(6540);
  });

  it("tiles the accrual exactly: no gap, no overlap, no date outside it", () => {
    // This is the invariant that makes summing the pieces a day count rather
    // than an approximation of one. Everything below depends on it.
    for (const { issue, settlement, first, frequency } of CASES) {
      const spans = quasiCouponSpans(issue, settlement, first, frequency);
      const where = `${iso(issue)}..${iso(settlement)} first ${iso(first)} freq ${frequency}`;
      expect(spans.length, where).toBeGreaterThan(0);
      expect(spans[0]?.from, where).toBe(issue);
      expect(spans[spans.length - 1]?.to, where).toBe(settlement);
      for (const [index, span] of spans.entries()) {
        if (index > 0) expect(span.from, where).toBe(spans[index - 1]?.to);
        expect(span.periodStart).toBeLessThanOrEqual(span.from);
        expect(span.periodEnd).toBeGreaterThanOrEqual(span.to);
        expect(span.to).toBeGreaterThan(span.from);
      }
    }
  });

  it("returns nothing for an accrual of no length, or a backwards one", () => {
    expect(quasiCouponSpans(s(2026, 5, 1), s(2026, 5, 1), s(2026, 9, 1), 2)).toEqual([]);
    expect(quasiCouponSpans(s(2026, 5, 1), s(2026, 4, 1), s(2026, 9, 1), 2)).toEqual([]);
  });

  it("puts every quasi-coupon date on a month end when the anchor is on one", () => {
    // The schedule is generated by the same function a priced bond's is, so
    // the end-of-month rule reaches the stub period too.
    const spans = quasiCouponSpans(s(2008, 3, 1), s(2009, 5, 1), s(2009, 8, 31), 2);
    expect(spans.map((span) => iso(span.periodStart))).toEqual([
      "2008-02-29",
      "2008-08-31",
      "2009-02-28",
    ]);
  });
});

describe("which bases a per-period accrual can move at all", () => {
  // Two independent reasons the sum can differ from the single span, and they
  // land on two different bases. Everything else agrees exactly.

  it("counts days additively on four of the five bases, exactly", () => {
    // An integer identity, so it is asserted as one. Splitting a span at a
    // quasi-coupon date and adding the pieces gives the same day count as
    // measuring it whole — on every basis but 30/360 US.
    for (const basis of [1, 2, 3, 4] as const) {
      for (const { issue, settlement, first, frequency } of CASES) {
        const spans = quasiCouponSpans(issue, settlement, first, frequency);
        let summed = 0;
        for (const span of spans) summed += basisDays(span.from, span.to, basis);
        expect(
          summed,
          `basis ${basis}: ${iso(issue)}..${iso(settlement)} first ${iso(first)} freq ${frequency}`,
        ).toBe(basisDays(issue, settlement, basis));
      }
    }
  });

  it("does not, on 30/360 US, because that count depends on both ends", () => {
    // The US rule pulls a 31st back to a 30th only when the *other* end of the
    // span is already at 30 or beyond, and treats a February month end as a
    // 30th. Either way the count of a stretch is not a property of the
    // stretch alone, so splitting it can change the total — which is why the
    // one 30/360 variant with extra rules is the one that moves here, and the
    // plain European one does not.
    let nonAdditive = 0;
    const differences = new Set<number>();
    for (const { issue, settlement, first, frequency } of CASES) {
      const spans = quasiCouponSpans(issue, settlement, first, frequency);
      let summed = 0;
      for (const span of spans) summed += basisDays(span.from, span.to, 0);
      const whole = basisDays(issue, settlement, 0);
      if (summed !== whole) {
        nonAdditive += 1;
        differences.add(summed - whole);
      }
    }
    expect(nonAdditive).toBe(188);
    expect([...differences].sort((a, b) => a - b)).toEqual([-4, -3, -2, -1, 1]);
  });

  it("has a constant period length on every basis but actual/actual", () => {
    // The second reason. A fixed denominator means the pieces share one, so
    // with additive day counts they telescope; actual/actual is the only basis
    // that measures the period it is in.
    for (const frequency of FREQUENCIES) {
      for (const basis of [0, 2, 3, 4] as const) {
        const lengths = new Set(
          CASES.filter((item) => item.frequency === frequency).flatMap((item) =>
            quasiCouponSpans(item.issue, item.settlement, item.first, frequency).map(
              (span) =>
                couponPeriodDays(span.periodStart, span.periodEnd, frequency, basis),
            ),
          ),
        );
        expect(lengths.size, `basis ${basis} freq ${frequency}`).toBe(1);
      }
      const actual = new Set(
        CASES.filter((item) => item.frequency === frequency).flatMap((item) =>
          quasiCouponSpans(item.issue, item.settlement, item.first, frequency).map(
            (span) => couponPeriodDays(span.periodStart, span.periodEnd, frequency, 1),
          ),
        ),
      );
      expect(actual.size, `actual/actual freq ${frequency}`).toBeGreaterThan(1);
    }
  });

  it("reproduces the single span to floating-point residue where both hold", () => {
    // Additive days over a constant denominator: the same number reached by a
    // different order of division, so a bound rather than an equality, and the
    // bound is what a handful of divisions costs.
    let worst = 0;
    for (const basis of [2, 3, 4] as const) {
      for (const { issue, settlement, first, frequency } of CASES) {
        worst = Math.max(
          worst,
          Math.abs(
            accruedYears(issue, settlement, first, frequency, basis) -
              yearFraction(issue, settlement, basis),
          ),
        );
      }
    }
    expect(worst).toBeLessThan(1e-15);
    // And the bound is doing work: a tolerance loose enough to cover the two
    // bases that genuinely move would have made this row vacuous.
    expect(worst).toBeGreaterThan(0);
  });

  it("differs materially on the two bases it does move, in both directions", () => {
    const extremes = (basis: DayCountBasis) => {
      let low = 0;
      let high = 0;
      for (const { issue, settlement, first, frequency } of CASES) {
        const summed = accruedYears(issue, settlement, first, frequency, basis);
        const span = yearFraction(issue, settlement, basis);
        const relative = (summed - span) / span;
        low = Math.min(low, relative);
        high = Math.max(high, relative);
      }
      return { low, high };
    };

    // Both signs on both bases, and neither is symmetric: a quasi-coupon
    // period longer than the notional one shrinks the accrual and a shorter
    // one inflates it, and short periods are further from the notional length
    // than long ones can be.
    const actualActual = extremes(1);
    expect(actualActual.low).toBeCloseTo(-0.00815, 5);
    expect(actualActual.high).toBeCloseTo(0.02528, 5);

    const us = extremes(0);
    expect(us.low).toBeCloseTo(-0.04878, 5);
    expect(us.high).toBeCloseTo(0.02632, 5);
  });
});

describe("ACCRINT", () => {
  it("still reproduces the published example", () => {
    // One quasi-coupon period, on a 30/360 basis: the case the two forms agree
    // on, which is why this figure could not have caught the defect.
    expect(
      plain.num("=ACCRINT(DATE(2008,3,1),DATE(2008,8,31),DATE(2008,5,1),0.1,1000,2,0)"),
    ).toBeCloseTo(16.66666667, 7);
  });

  it("answers the same example differently on actual/actual", () => {
    // 1 March to 1 May is 61 days of a 184-day quasi-coupon period, not 61
    // days of a 366-day year.
    expect(
      plain.num("=ACCRINT(DATE(2008,3,1),DATE(2008,8,31),DATE(2008,5,1),0.1,1000,2,1)"),
    ).toBeCloseTo(16.57608696, 7);
    expect(
      1000 * 0.05 * (61 / 184),
    ).toBeCloseTo(16.57608696, 7);
  });

  it("takes its answer from the first-interest date, which it used to discard", () => {
    // The parameter test. Same issue, settlement, rate and par throughout;
    // only the date that anchors the quasi-coupon schedule moves.
    const at = (first: string) =>
      plain.num(`=ACCRINT(DATE(2008,3,1),${first},DATE(2008,5,1),0.1,1000,2,1)`);
    const august = at("DATE(2008,8,31)");
    const october = at("DATE(2008,10,15)");
    const june = at("DATE(2008,6,30)");
    expect(august).toBeCloseTo(16.57608696, 7);
    expect(october).toBeCloseTo(16.66666667, 7);
    expect(june).toBeCloseTo(16.75824176, 7);
    // A spread of 1.1% of the accrual, from a parameter that could not reach
    // the result before.
    expect((june - august) / august).toBeCloseTo(0.011, 3);
  });

  it("is blind to that date on the bases whose periods are all one length", () => {
    // Both halves. On these three the first-interest date cannot matter, and
    // saying so is what makes the row above a finding rather than a fixture.
    for (const basis of [2, 3, 4] as const) {
      const values = [
        "DATE(2008,8,31)",
        "DATE(2008,10,15)",
        "DATE(2008,6,30)",
        "DATE(2009,1,31)",
      ].map((first) =>
        plain.num(`=ACCRINT(DATE(2008,3,1),${first},DATE(2008,5,1),0.1,1000,2,${basis})`),
      );
      for (const value of values) {
        expect(value, `basis ${basis}`).toBeCloseTo(values[0] as number, 12);
      }
    }
  });

  it("accrues from issue or from the first interest date, as asked", () => {
    const from = (method: string) =>
      plain.num(
        `=ACCRINT(DATE(2026,1,15),DATE(2026,7,15),DATE(2027,3,1),0.1,1000,2,1${method})`,
      );
    expect(from("")).toBeCloseTo(112.43093923, 7);
    expect(from(",TRUE")).toBe(from(""));
    expect(from(",FALSE")).toBeCloseTo(62.43093923, 7);
    // The difference is exactly the interest over the stretch the second
    // convention drops, which is one whole coupon period and then some.
    expect(from("") - from(",FALSE")).toBeCloseTo(50, 9);
  });

  it("gives both conventions the same answer at or before the first interest date", () => {
    // Which is why the flag could not matter while the accrual was one span.
    for (const basis of ALL_BASES) {
      const issued = `DATE(2026,1,15),DATE(2026,7,15),DATE(2026,5,1),0.1,1000,2,${basis}`;
      expect(plain.num(`=ACCRINT(${issued},TRUE)`), `basis ${basis}`).toBe(
        plain.num(`=ACCRINT(${issued},FALSE)`),
      );
    }
  });

  it("still refuses the terms that are not an accrual", () => {
    expect(
      plain.display("=ACCRINT(DATE(2008,5,1),DATE(2008,3,1),DATE(2008,8,1),0.1,1000,2,0)"),
    ).toBe("#NUM!");
    expect(
      plain.display("=ACCRINT(DATE(2008,3,1),DATE(2008,8,1),DATE(2008,3,1),0.1,1000,2,0)"),
    ).toBe("#NUM!");
    expect(
      plain.display("=ACCRINT(DATE(2008,3,1),DATE(2008,8,1),DATE(2008,5,1),0,1000,2,0)"),
    ).toBe("#NUM!");
    expect(
      plain.display("=ACCRINT(DATE(2008,3,1),DATE(2008,8,1),DATE(2008,5,1),0.1,0,2,0)"),
    ).toBe("#NUM!");
    expect(
      plain.display("=ACCRINT(DATE(2008,3,1),DATE(2008,8,1),DATE(2008,5,1),0.1,1000,3,0)"),
    ).toBe("#NUM!");
  });

  it("grows with the accrual and scales with par and rate", () => {
    const at = (settlement: string) =>
      plain.num(`=ACCRINT(DATE(2026,1,15),DATE(2026,7,15),${settlement},0.1,1000,2,1)`);
    expect(at("DATE(2026,3,1)")).toBeLessThan(at("DATE(2026,5,1)"));
    expect(at("DATE(2026,5,1)")).toBeLessThan(at("DATE(2026,7,1)"));
    const base = plain.num(
      "=ACCRINT(DATE(2026,1,15),DATE(2026,7,15),DATE(2026,5,1),0.1,1000,2,1)",
    );
    expect(
      plain.num("=ACCRINT(DATE(2026,1,15),DATE(2026,7,15),DATE(2026,5,1),0.1,2000,2,1)"),
    ).toBeCloseTo(2 * base, 9);
    expect(
      plain.num("=ACCRINT(DATE(2026,1,15),DATE(2026,7,15),DATE(2026,5,1),0.2,1000,2,1)"),
    ).toBeCloseTo(2 * base, 9);
  });
});
